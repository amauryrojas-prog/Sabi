$historySection += "| Date | Draw # | Winning Numbers |`r`n"
$historySection += "| :--- | :---: | :---: |`r`n"

foreach ($item in $sortedData) {
    $numsStr = @()
    foreach ($n in $item.numbers) {
        $numsStr += $n.ToString().PadLeft(2, '0')
    }
    $numsJoined = $numsStr -join " - "
    $historySection += "| " + (Format-DateStr $item.date) + " | " + $item.draw + " | " + $numsJoined + " |`r`n"
}

[System.IO.File]::WriteAllText($mdPath, ($headerMd + $historySection), [System.Text.Encoding]::UTF8)
Write-Host "Success! Total draws: $($sortedData.Count)"
