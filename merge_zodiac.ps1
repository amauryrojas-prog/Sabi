function Parse-Date($dateStr) {
    $parts = $dateStr.Trim() -split '[\s,]+'
    if ($parts.Length -ge 3) {
        $m = $monthMap[$parts[0].Substring(0,3)]
        $d = $parts[1].PadLeft(2, '0')
        $y = $parts[2]
        return "$y-$m-$d"
    }
    return $dateStr
}

